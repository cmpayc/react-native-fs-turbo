/**
 * React Native SwiftPM autolinking plugin for react-native-fs-turbo.
 *
 * Runs on `npx react-native spm add` / `update` and on the Xcode
 * "Sync SPM Autolinking" build phase. It writes RNFSTurboConfig.generated.h
 * with the build options into the app's own ios/build tree (not into
 * node_modules, which a monorepo may share between apps), so changing them
 * only needs `spm update` (the SwiftPM counterpart of `pod install`) — no
 * Swift package cache resets.
 *
 * Options (app package.json):
 *   "rnFsTurbo": { "useEncryption": true }
 * The RNFSTURBO_USE_ENCRYPTION=1|0 environment variable overrides it.
 */

'use strict';

const fs = require('node:fs');
const path = require('node:path');

const PACKAGE_NAME = 'RNFSTurbo';
const HEADER_NAME = 'RNFSTurboConfig.generated.h';

function findAppPackageJson(startDirs) {
  for (const start of startDirs) {
    if (!start) continue;
    let dir = path.resolve(start);
    for (;;) {
      const candidate = path.join(dir, 'package.json');
      if (fs.existsSync(candidate)) {
        try {
          const json = JSON.parse(fs.readFileSync(candidate, 'utf8'));
          if (json.name !== 'react-native-fs-turbo') {
            return {path: candidate, json};
          }
        } catch (e) {
          // Unreadable package.json — keep looking further up.
        }
      }
      const parent = path.dirname(dir);
      if (parent === dir) break;
      dir = parent;
    }
  }
  return null;
}

function parseBool(value) {
  return ['1', 'true', 'yes'].includes(String(value).trim().toLowerCase());
}

module.exports = function rnfsTurboAutolinkingPlugin(context) {
  const appPackage = findAppPackageJson([context.projectRoot, context.appRoot]);
  const options = (appPackage && appPackage.json.rnFsTurbo) || {};

  const envValue = process.env.RNFSTURBO_USE_ENCRYPTION;
  const useEncryption =
    envValue != null && envValue !== ''
      ? parseBool(envValue)
      : options.useEncryption === true;

  const content =
    '// AUTO-GENERATED by react-native-fs-turbo/spm/autolinking-plugin.js — do not edit.\n' +
    '// Change "rnFsTurbo" in your app\'s package.json and run `npx react-native spm update`.\n\n' +
    '#pragma once\n\n' +
    (useEncryption ? '#define RNFSTURBO_USE_ENCRYPTION 1\n' : '// Encryption disabled\n');

  const libRoot = path.resolve(__dirname, '..');
  const aliasDir = path.join(context.outputDir, 'plugin-libs');
  const aliasPath = path.join(aliasDir, PACKAGE_NAME);
  fs.mkdirSync(aliasDir, {recursive: true});
  let currentTarget = null;
  try {
    currentTarget = fs.readlinkSync(aliasPath);
  } catch (e) {}
  if (currentTarget !== libRoot) {
    fs.rmSync(aliasPath, {recursive: true, force: true});
    fs.symlinkSync(libRoot, aliasPath, 'dir');
  }

  const headerPath = path.join(aliasDir, HEADER_NAME);
  let current = null;
  try {
    current = fs.readFileSync(headerPath, 'utf8');
  } catch (e) {}
  if (current !== content) {
    fs.writeFileSync(headerPath, content);
  }

  return {
    packageDependencies: [
      {name: PACKAGE_NAME, path: `plugin-libs/${PACKAGE_NAME}`},
    ],
    productDependencies: [{name: PACKAGE_NAME, package: PACKAGE_NAME}],
    watchPaths: appPackage ? [appPackage.path] : [],
  };
};
